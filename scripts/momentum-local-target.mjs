import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

export function parseEnvironment(text) {
  const values = {};
  for (const sourceLine of text.split(/\r?\n/)) {
    const line = sourceLine.trim();
    if (!line || line.startsWith('#')) continue;
    const separator = line.indexOf('=');
    if (separator < 1) continue;
    const key = line.slice(0, separator).trim();
    const raw = line.slice(separator + 1).trim();
    values[key] = raw.replace(/^(['"])(.*)\1$/, '$2');
  }
  return values;
}

export function verifyLocalTarget({ envPath = '.env.local', requireKeys = true } = {}) {
  const absolutePath = resolve(envPath);
  let values;
  try {
    values = parseEnvironment(readFileSync(absolutePath, 'utf8'));
  } catch (error) {
    throw new Error(`Local environment file is required at ${absolutePath}: ${error.message}`);
  }

  const rawUrl = values.EXPO_PUBLIC_SUPABASE_URL;
  let url;
  try {
    url = new URL(rawUrl);
  } catch {
    throw new Error('EXPO_PUBLIC_SUPABASE_URL must be a valid local URL');
  }
  const localHosts = new Set(['127.0.0.1', 'localhost']);
  if (url.protocol !== 'http:' || !localHosts.has(url.hostname) || url.port !== '54321') {
    throw new Error(`Refusing non-local Supabase target: ${url.origin}`);
  }

  if (requireKeys) {
    for (const key of ['EXPO_PUBLIC_SUPABASE_ANON_KEY', 'SUPABASE_SERVICE_ROLE_KEY']) {
      const value = values[key] ?? '';
      if (!value || value.startsWith('<') || value.length < 20) {
        throw new Error(`${key} must contain the credential generated by the local Supabase stack`);
      }
    }
  }

  return { envPath: absolutePath, origin: url.origin, values };
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;
if (isMain) {
  try {
    const result = verifyLocalTarget({ envPath: process.argv[2] ?? '.env.local' });
    console.log(JSON.stringify({ envPath: result.envPath, local: true, target: result.origin }));
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
